import { chromium } from 'playwright';
const browser = await chromium.launch({args:['--no-sandbox']});
const page = await browser.newPage();
await page.goto('http://127.0.0.1:8080/');
await page.waitForTimeout(5000);
await page.getByRole('button', { name: 'Mark done', exact: true }).first().click();
await page.getByRole('button', { name: 'Mark not done', exact: true }).first().click();
await page.locator('nav').getByRole('button', { name: 'Pipeline', exact: true }).click();
await page.getByPlaceholder('What they need').fill('Glass UI QA lead');
await page.getByPlaceholder('Town or agency').fill('Boston');
await page.getByRole('button', { name: 'Add to the desk' }).click();
const card = page.locator('li').filter({hasText:'Glass UI QA lead'});
await card.getByRole('button',{name:'Quoted',exact:true}).click();
await card.getByRole('button',{name:'Remove lead'}).click();
await page.locator('nav').getByRole('button', { name: 'Coach', exact: true }).click();
await page.getByRole('heading',{name:'The coach',exact:true}).waitFor();
await page.screenshot({path:'screenshots/glass-coach.png'});
console.log('Checklist, tabs, add/status/remove lead and coach layout passed.');
await browser.close();
